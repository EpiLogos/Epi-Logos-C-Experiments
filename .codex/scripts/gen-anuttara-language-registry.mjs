#!/usr/bin/env node
/**
 * gen-anuttara-language-registry.mjs — Tranche 01.T1.10 registry generator.
 *
 * Parses the canonical 109-node Anuttara language map dataset
 * (Idea/Bimba/Map/datasets/anuttara-deep/anuttara-language-map.md) and emits
 * the M0-alphabet rows of ANUTTARA_LANGUAGE_REGISTRY as a C include fragment
 * at Body/S/S0/epi-lib/src/anuttara_language_registry.inc.
 *
 * The 19 QL-closure entries (7 psychoid bases + 12 coordinate types per
 * M0-ARCHITECTURE §11) are NOT generated here — they are hand-authored in
 * anuttara_language.c because they are M1-closure law, not dataset rows.
 *
 * Deterministic: same dataset in, same fragment out. Re-run when the
 * anuttara-deep export matures (the 109 may grow; the .inc carries the count).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const datasetPath = resolve(
  repoRoot,
  "Idea/Bimba/Map/datasets/anuttara-deep/anuttara-language-map.md"
);
const outPath = resolve(
  repoRoot,
  "Body/S/S0/epi-lib/src/anuttara_language_registry.inc"
);

const PIPE_SENTINEL = "";

function splitRow(line) {
  return line
    .replace(/\\\|/g, PIPE_SENTINEL)
    .split("|")
    .map((cell) => cell.replaceAll(PIPE_SENTINEL, "|").trim());
}

function stripTicks(value) {
  const trimmed = value.trim();
  if (trimmed.startsWith("`") && trimmed.endsWith("`") && trimmed.length >= 2) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

function cEscape(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

/* Pack "M0-a-b-c" (simple integer components 0-15, up to depth 3) into the
 * m0.h M0C nibble encoding: M0C(0, a, b, c); missing trailing components are
 * 0xF. Compound coordinates like "M0-(4.0/1)" are unpackable -> 0xFFFF. */
function packCoordinate(coord) {
  if (coord === "M0") return 0x0fff; /* M0C_ROOT(0) */
  const m = coord.match(/^M0-(\d+)(?:-(\d+))?(?:-(\d+))?$/);
  if (!m) return 0xffff;
  const parts = [m[1], m[2], m[3]].map((p) =>
    p === undefined ? 0xf : Number(p)
  );
  if (parts.some((p) => Number.isNaN(p) || p > 0xf)) return 0xffff;
  return ((0 << 12) | (parts[0] << 8) | (parts[1] << 4) | parts[2]) & 0xffff;
}

const lines = readFileSync(datasetPath, "utf8").split("\n");
const entries = [];
for (const line of lines) {
  if (!/^\|\s*`M0/.test(line)) continue;
  const cells = splitRow(line);
  /* cells[0] is empty (leading pipe): [ , coordinate, name, symbol, ...] */
  const coordinate = stripTicks(cells[1] ?? "");
  const name = stripTicks(cells[2] ?? "");
  const symbol = stripTicks(cells[3] ?? "");
  if (!coordinate) continue;
  entries.push({ coordinate, name, symbol });
}

if (entries.length === 0) {
  console.error("No M0 rows parsed — dataset format changed?");
  process.exit(1);
}

const rows = entries
  .map((e) => {
    const packed = packCoordinate(e.coordinate);
    const symbolField =
      e.symbol === ""
        ? "    .symbol = NULL, /* canonical absence */"
        : `    .symbol = "${cEscape(e.symbol)}",`;
    return [
      "  {",
      `    .coordinate = "${cEscape(e.coordinate)}",`,
      symbolField,
      `    .name = "${cEscape(e.name)}",`,
      "    .kind = ANUTTARA_ENTRY_M0_ALPHABET,",
      `    .packed = 0x${packed.toString(16).toUpperCase().padStart(4, "0")}u,`,
      "  },",
    ].join("\n");
  })
  .join("\n");

const fragment = `/*
 * anuttara_language_registry.inc — GENERATED by
 * .codex/scripts/gen-anuttara-language-registry.mjs
 * Source: Idea/Bimba/Map/datasets/anuttara-deep/anuttara-language-map.md
 * (verbatim c_1_* export of the ${entries.length}-node Anuttara M0 alphabet).
 * Do not edit manually — re-run the generator when the dataset matures.
 */

#define ANUTTARA_LANGUAGE_M0_ALPHABET_COUNT ${entries.length}u

#define ANUTTARA_LANGUAGE_M0_ALPHABET_ROWS \\
${rows
  .split("\n")
  .map((l) => l + " \\")
  .join("\n")}

`;

writeFileSync(outPath, fragment);
console.log(`wrote ${outPath}: ${entries.length} M0 alphabet entries`);
