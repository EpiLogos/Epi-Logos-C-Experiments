/** A kernel phaseSpace at a given degree, in the EXACT wire shape the E1
 *  baseline fixture (portal-core contract-inventory/baseline-profile.json)
 *  pins — lensCarrier entries mirror phase_space.rs CLOCK_LENSES_16. */
function kernelPhaseSpace(degree720: number): PhaseSpaceBoundary {
    const degree360 = degree720 % 360;
    return {
        degree720,
        degree360,
        plane: degree720 < 360 ? 'primary-codon' : 'shadow-hexagram',
        activeValence:
            degree720 < 360
                ? { kind: 'codon', upperPair: 1, lowerPair: 2, codonClass: 0, isNonDual: true }
                : { kind: 'hexagram', hexagramId: 10, lineActive: 4 },
        node: {
            degree360,
            exactDegree720: degree360 * 2,
            zodiacSign: Math.floor(degree360 / 30),
            zodiacDegree: degree360 % 30,
            decan36: Math.floor(degree360 / 10),
            decanPosition: degree360 % 10,
            isBackboneNode: degree360 % 15 === 0,
            hexagramId: 10,
            hexagramLineActive: 4,
            isNonDualCodon: true,
            codonClass: 0,
            codonUpperPair: 1,
            codonLowerPair: 2,
            tarotCardId: 0,
            decanPlanet: 4,
            decanElement: 0,
            decanChakra: 2,
            degreeTick12: Math.floor(degree360 / 30),
            strand: 0,
            drRing: 0,
            m1AnandaValue: 0,
            m0Archetype: 0,
            shadowDegree: (degree360 + 360) % 720,
            polarOpposite: (degree360 + 180) % 360,
            enneadicChamber: Math.floor(degree360 / 40),
            chamberDayNight: degree360 % 40 < 20 ? 0 : 1,
            lensSegment: CLOCK_LENSES.map(lens => Math.floor(degree360 / lens.slice))
        },
        lensCarrier: CLOCK_LENSES.map((lens, i) => ({
            lensIndex: i,
            slice: lens.slice,
            sections: lens.sections,
            name: lens.name,
            temporalCanon: lens.temporalCanon,
            segment: Math.floor(degree360 / lens.slice),
            degreeInSegment: degree360 % lens.slice,
            phase01: (degree360 % lens.slice) / lens.slice
        })),
        fibonacciGround: {
            position: Math.floor(degree360 / 6),
            digit: 3,
            phase01: (degree360 % 6) / 6,
            temporalCanon: true
        },
        authority: 'epi-lib::CLOCK_DEGREE_LUT (.rodata, 384 = 360 + 24 = 64x6)'
    };
}

function profileAt(degree720: number, extra: Record<string, unknown> = {}): unknown {
    return {
        harmonicProfile: {
            tick12: Math.floor((degree720 % 360) / 30),
            degree720,
            degree360: degree720 % 360,
            ...extra
        }
    };
}

function record(generation: number, profile: unknown): TickRecord {
    const hp = harmonicSnapshot(profile);
    return { generation, hp, kleinValence: 1, axisFlipped: false };
}

const LIVE: EngineControls = { divisionIndex: 6, live: true, tickAtMs: 0, flipAtMs: -1 };

describe('app lens table vs kernel table', () => {
    it('CLOCK_LENSES mirrors the kernel CLOCK_LENSES_16 row-for-row (kernel-blessed baseline fixture)', () => {
        // E3-verifier closure: the local table is display fallback only, but it
        // must never drift from the kernel — pin every row against the real
        // portal-core baseline (generated by the kernel itself).
        // vitest cwd is the app root (Body/M/pratibimba-app)
        const repoRoot = resolve(process.cwd(), '..', '..', '..');
        const baseline = JSON.parse(
            readFileSync(
                resolve(repoRoot, 'Body/S/S0/portal-core/contract-inventory/baseline-profile.json'),
                'utf8'
            )
        ) as { phaseSpace: PhaseSpaceBoundary };
        const carrier = baseline.phaseSpace.lensCarrier;
        expect(carrier).toHaveLength(16);
        carrier.forEach((row, i) => {
            expect({
                name: row.name,
                slice: row.slice,
                sections: row.sections,
                temporalCanon: row.temporalCanon
            }).toEqual({
                name: CLOCK_LENSES[i].name,
                slice: CLOCK_LENSES[i].slice,
                sections: CLOCK_LENSES[i].sections,
                temporalCanon: CLOCK_LENSES[i].temporalCanon
            });
        });
    });
});

describe('division modulator (the E2 engine half)', () => {
    it('carries the tick from the KERNEL lensCarrier when phaseSpace is present — even against local arithmetic', () => {
        const base = kernelPhaseSpace(144);
        // doctor the kernel segment so it cannot be confused with a local
        // computation: if the frame carries 99, the kernel won
        const ps: PhaseSpaceBoundary = {
            ...base,
            lensCarrier: base.lensCarrier.map((lens, i) =>
                i === 6 ? { ...lens, segment: 99, phase01: 0.5 } : lens
            )
        };
        const hp = harmonicSnapshot(profileAt(144, { phaseSpace: ps }));
        const division = deriveDivision(hp, 6);
        expect(division.source).toBe('kernel');
        expect(division.segment).toBe(99);
        expect(division.phase01).toBe(0.5);
        expect(division.fibonacci).toEqual(ps.fibonacciGround);
    });

    it('falls back to local arithmetic (§4 formula, honest source) when phaseSpace is absent', () => {
        const hp = harmonicSnapshot(profileAt(144));
        const division = deriveDivision(hp, 6); // Zodiacal, slice 12
        expect(division.source).toBe('local');
        expect(division.segment).toBe(12); // the app-pinned 144° case: 144/12
        expect(division.degreeInSegment).toBe(0);
        expect(division.fibonacci).toBeNull(); // Pisano digit law is kernel-only
    });

    it('reports null segment (division unavailable) with no degree at all', () => {
        const hp = harmonicSnapshot({ harmonicProfile: {} });
        expect(deriveDivision(hp, 6).segment).toBeNull();
    });

    it('gears rhythm by the kernel temporal canon: exactly the 24/12/4-section divisions subdivide', () => {
        const temporal = CLOCK_LENSES.filter(lens => lens.temporalCanon).map(l => l.sections);
        expect(temporal.sort((a, b) => a - b)).toEqual([4, 12, 24]);
        for (let i = 0; i < CLOCK_LENSES.length; i++) {
            const lens = CLOCK_LENSES[i];
            expect(rhythmicSubdivision(lens)).toBe(lens.temporalCanon ? lens.sections : 1);
            const hp = harmonicSnapshot(profileAt(144, { phaseSpace: kernelPhaseSpace(144) }));
            expect(deriveDivision(hp, i).subdivision).toBe(lens.temporalCanon ? lens.sections : 1);
        }
    });
});

describe('tonality modulator (84-state namespace law)', () => {
    it('never merges with the division aperture: changing the division leaves (lens, mode) untouched', () => {
        const rec = record(5, profileAt(144, { lensMode: { lens: 7, mode: 3 } }));
        const zodiacal = deriveFrame(rec, null, { ...LIVE, divisionIndex: 6 }, 0, 0.5);
        const quadrant = deriveFrame(rec, null, { ...LIVE, divisionIndex: 13 }, 0, 0.5);
        expect(zodiacal.tonality).toMatchObject({ lens: 7, mode: 3 });
        expect(quadrant.tonality).toEqual(zodiacal.tonality);
        expect(zodiacal.division.name).toBe('Zodiacal');
        expect(quadrant.division.name).toBe('Quadrant');
    });

    it('is null (not fabricated) when the profile carries no lensMode', () => {
        const rec = record(5, profileAt(144));
        expect(deriveFrame(rec, null, LIVE, 0, 0).tonality).toBeNull();
    });

    it('surfaces KERNEL tonality labels verbatim — lensLabel/modeName/84-index, never local tables (E7)', () => {
        const rec = record(
            6,
            profileAt(144, {
                lensMode: { lens: 4, mode: 2 },
                chromatic: { note: 'G#' },
                codonRotationProjection: {
                    codonId: 12,
                    rotation: 2,
                    lensLabel: 'L4',
                    modeName: 'Phrygian'
                },
                modalResonator: { schemaVersion: 1, lensMode: { lens: 4, mode: 2, lensModeIndex: 30 } }
            })
        );
        const tonality = deriveFrame(rec, null, LIVE, 0, 0).tonality;
        expect(tonality).toEqual({
            lens: 4,
            mode: 2,
            lensLabel: 'L4',
            modeName: 'Phrygian',
            lensModeIndex: 30, // kernel-computed lens·7+mode — never derived here
            anchorNote: 'G#'
        });
        // labels absent → null, never invented
        const bare = deriveFrame(
            record(7, profileAt(144, { lensMode: { lens: 4, mode: 2 } })),
            null,
            LIVE,
            0,
            0
        ).tonality;
        expect(bare?.modeName).toBeNull();
        expect(bare?.lensModeIndex).toBeNull();
    });
});

describe('oscillator determinism (the scrubbable 5-tuple)', () => {
    it('yields byte-identical frames for identical (records, controls, frac)', () => {
        const prev = record(4, profileAt(419, { lensMode: { lens: 1, mode: 2 } }));
        const cur = record(5, profileAt(420, { lensMode: { lens: 1, mode: 2 } }));
        const a = deriveFrame(cur, prev, LIVE, 1234, 0.37);
        const b = deriveFrame(cur, prev, LIVE, 1234, 0.37);
        expect(JSON.stringify(a)).toBe(JSON.stringify(b));
    });

    it('sweeps continuously between generations and unwraps the 720 möbius boundary', () => {
        const prev = record(4, profileAt(719));
        const cur = record(5, profileAt(0));
        const start = deriveFrame(cur, prev, LIVE, 0, 0).oscillator.sweepAngle;
        const end = deriveFrame(cur, prev, LIVE, 0, 1).oscillator.sweepAngle;
        expect(start).toBeCloseTo((719 / 720) * Math.PI * 4);
        expect(end).toBeCloseTo((720 / 720) * Math.PI * 4); // forward across the wrap, not a rewind
    });
});

